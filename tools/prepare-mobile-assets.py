"""Create mobile WebP derivatives; retain original art and alpha, never regenerate artwork."""
from pathlib import Path
import json
from PIL import Image

root = Path(__file__).resolve().parents[1]
assets = root / 'public/assets'
inputs = sorted(p for p in (assets/'storybook').iterdir() if p.suffix in {'.png', '.webp'} and p.name!='cover-v7.webp')
inputs += [assets/'atelier/timber-grain.webp']
mapping, report = {}, []
for source in inputs:
    relative = source.relative_to(assets).as_posix()
    destination = assets/'mobile-v1'/Path(relative).with_suffix('.webp')
    destination.parent.mkdir(parents=True, exist_ok=True)
    with Image.open(source) as original:
        image = original.copy()
        limit = (1008 if 'atlas' in source.name else 640 if ('pedestrian-' in source.name or '-keeper-' in source.name)
                 else 512 if source.stem in {'plane-tree','vine-cluster','timber-grain'} else 832 if source.stem=='cover-v7' else 896)
        image.thumbnail((limit, limit), Image.Resampling.LANCZOS)
        image.save(destination, format='WEBP', quality=78, method=6, alpha_quality=100)
        mapping[relative] = destination.relative_to(assets).as_posix()
        report.append({'original': relative, 'mobile': mapping[relative], 'originalBytes': source.stat().st_size,
                       'mobileBytes': destination.stat().st_size, 'originalSize': original.size, 'mobileSize': image.size,
                       'originalPixels': original.width*original.height, 'mobilePixels': image.width*image.height})
with Image.open(assets/'storybook/cover-v7.png') as cover:
    cover.save(assets/'storybook/cover-v7.webp', format='WEBP', quality=85, method=6)
(root/'src/atelier/mobileAssetManifest.ts').write_text('// Generated by tools/prepare-mobile-assets.py; originals remain available for desktop.\n'
    + 'export const mobileAssetManifest:Readonly<Record<string,string>> = '+json.dumps(mapping,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
(root/'docs/mobile-assets.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
print(json.dumps({'variants': len(report), 'originalBytes':sum(r['originalBytes'] for r in report),
                  'mobileBytes':sum(r['mobileBytes'] for r in report), 'originalPixels':sum(r['originalPixels'] for r in report),
                  'mobilePixels':sum(r['mobilePixels'] for r in report)}))
